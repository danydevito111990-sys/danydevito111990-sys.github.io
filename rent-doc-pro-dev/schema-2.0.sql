-- RENT DOC PRO 2.0 DEV: initial schema, import only into dedicated empty rentdoc_dev database.
CREATE TABLE IF NOT EXISTS schema_migrations (
 version VARCHAR(32) PRIMARY KEY, applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 login VARCHAR(120) NOT NULL UNIQUE,
 display_name VARCHAR(200) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('owner','admin','worker','viewer','custom') NOT NULL DEFAULT 'worker',
 owner_slot TINYINT GENERATED ALWAYS AS (CASE WHEN role='owner' THEN 1 ELSE NULL END) STORED UNIQUE,
 recovery_email VARCHAR(254) NULL,
 recovery_verified_at DATETIME NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
 session_version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS user_permissions (
 user_id BIGINT UNSIGNED NOT NULL, permission_key VARCHAR(64) NOT NULL,
 PRIMARY KEY(user_id,permission_key), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS password_reset_tokens (
 token_hash BINARY(32) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL, used_at DATETIME NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NULL,
 action_key VARCHAR(80) NOT NULL, entity_type VARCHAR(80) NULL, entity_id VARCHAR(80) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(created_at), FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS login_attempts (
 bucket BINARY(32) PRIMARY KEY, attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_started DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
